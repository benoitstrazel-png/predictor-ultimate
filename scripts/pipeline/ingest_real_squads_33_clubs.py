def generate_season_squad(club_slug, base_players, season_year):
    """
    Génère un effectif cohérent pour une saison donnée à partir de la base de joueurs réels.
    """
    season_str = f"{season_year}-{season_year+1}"
    players_out = []
    
    for idx, p in enumerate(base_players, start=1):
        name, num, pos_full, pos_code, nat, base_age, base_val, fotmob_id, apps, goals, assists = p
        
        # Ajuster l'âge selon la saison
        age_offset = season_year - 2026
        adj_age = base_age + age_offset
        
        # ID unique déterministe
        p_slug = re.sub(r'[^a-z0-9]', '_', name.lower())
        p_id = f"p_{club_slug}_{season_year}_{idx}"
        
        joined_date = "2024-07-01" if season_year == 2024 else ("2025-07-01" if season_year == 2025 else "2026-07-01")
        
        players_out.append({
            "id": p_id,
            "tm_id": fotmob_id,
            "name": name,
            "number": num,
            "position": pos_full,
            "role_category": pos_code,
            "nationality": nat,
            "age": adj_age,
            "market_value": base_val,
            "joined_date": joined_date,
            "left_date": None,
            "contract_until": "2028-06-30",
            "status": "ACTIVE",
            "photo": f"https://images.fotmob.com/image_resources/playerimages/{fotmob_id}.png",
            "stats": {
                "appearances": max(5, apps + (age_offset * 2)),
                "goals": max(0, goals + (1 if goals > 2 and age_offset < 0 else 0)),
                "assists": max(0, assists + (1 if assists > 2 and age_offset < 0 else 0)),
                "yellowCards": 2,
                "redCards": 0
            }
        })
        
    return players_out

